(function(){
 'use strict';
 const state=window.DigSkoleStage;
 const output=document.getElementById('kvalitet-detail');
 const label=document.getElementById('kvalitet-current');
 const practiceNames=window.GENKI_PRACTICES;
 const digital=window.DIGSKOLE_DIGITAL_PRACTICES;
 const all=window.DIGSKOLE_FAGLIG_KVALITET;
 if(!state||!output||!digital||!all||!practiceNames)return;
 function render(){
  const stage=state.get();
  const current=window.DigSkolePractice && window.DigSkolePractice.get ? window.DigSkolePractice.get() : (new URLSearchParams(location.search).get('praksis')||'undersoke');
  const p=all[current]&&all[current][stage];
  const scene=digital[current]&&digital[current][stage];
  if(!p||!scene)return;
  const e=s=>state.text(s);
  document.querySelectorAll('[data-qual-learners]').forEach(el=>{
   const forms={genitive:'elevenes',singular:'eleven','singular-genitive':'elevens'};
   el.textContent=state.raw(forms[el.dataset.qualLearners]||'elevenes');
  });
  const headings=['Hva kjennetegner faglig kvalitet her?','Mulige tegn i elevenes arbeid','Hva bør læreren undersøke videre?','Hvordan kan læreren følge opp?'];
  if(label)label.textContent=`${practiceNames.items[current].title} · ${state.stages[stage].label} · ${scene[0]}`;
  output.innerHTML=`<article class="qual-card" aria-label="Faglig kvalitet i ${e(scene[1])}">
    <div class="qual-eyebrow">Samme undervisningseksempel · ${e(scene[0])}</div>
    <h3>${e(scene[1])}</h3>
    <div class="qual-grid">${p.slice(0,4).map((v,i)=>`<section class="qual-cell qual-cell-${i+1}"><span class="qual-number">0${i+1}</span><h4>${e(headings[i])}</h4><p>${e(v)}</p></section>`).join('')}</div>
    <div class="qual-discuss"><span>Til kollegasamtalen</span><p>${e(p[4])}</p></div>
  </article>`;
 }
 window.addEventListener('digskole-stagechange',render);
 window.addEventListener('digskole-practicechange',render);
 render();
})();
